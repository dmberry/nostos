    'target ever built. It is a <b>single point of failure</b> for the privacy of a',
    'whole society. Break in once, or corrupt one insider, or lean on the holder',
    'with the right pressure, and you do not get one person’s secrets, you get',
    'everyone’s. Cryptographers spend their lives removing single points of',
