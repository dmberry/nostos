// The lists article. It leans on Harper throughout, and says so on the page,
// because the recursive definition of a list is the single idea that makes
// everything else about this language make sense, and Harper states it better
// than a paraphrase would. Quotation is short and attributed; the References
// page carries the full citation.
function listsPage(host) {
  return [
    `<h1>${TITLE.lists}</h1>`,
    '<p>A list is a finite sequence of values, all of the same kind. The',
    'definition worth learning is not that one, though, but the recursive one,',
    'because it is the shape every function over a list will take.</p>',
    '<h2>The two cases</h2>',
    '<p>Harper puts it plainly: a list',
    '<i>"is either empty, or it consists of a value of type t followed by a t',
    'list"</i> (Harper 1993, p.9). That is the whole definition, and it has',
    'exactly two cases, which is why every function you write over a list will',
    'have exactly two cases too.</p>',
    '<p>The empty list is written <b>nil</b>. A value on the front of a list is',
    'written with <b>::</b>, pronounced <i>cons</i>, after the LISP function of',
    'that name.</p>',
    code('nil', '&gt; []',
         '1 :: nil', '&gt; [1]',
         '1 :: 2 :: 3 :: nil', '&gt; [1, 2, 3]'),
    '<p>The bracket notation is an abbreviation for the same thing, and you may',
    'use whichever reads better:</p>',
    code('[1, 2, 3]', '&gt; [1, 2, 3]',
         '1 :: [2, 3]', '&gt; [1, 2, 3]'),
    '<p><b>:: groups to the right.</b> <code>1 :: 2 :: nil</code> is',
    '<code>1 :: (2 :: nil)</code>. It has to be: read the other way it would try',
    'to put a list on the front of the number 2 and fail on the first step.</p>',
    '<h2>Taking one apart</h2>',
    '<p>Three verbs. <b>hd</b> gives the first element, <b>tl</b> gives what is',
    'left after it, and <b>length</b> counts.</p>',
    code('hd [1, 2, 3]', '&gt; 1',
         'tl [1, 2, 3]', '&gt; [2, 3]',
         'length [1, 2, 3]', '&gt; 3',
         'hd (tl [1, 2, 3])', '&gt; 2'),
    '<p><b>hd nil</b> and <b>tl nil</b> are errors, and correctly so: there is',
    'no first element of an empty list. Test with <code>length</code> before you',
    'take a list apart, and that test is the base case of your recursion.</p>',
    '<h2>Writing map</h2>',
    '<p>This dialect has no map. It does not need one, and writing it is the',
    'exercise that shows you have understood the two cases.</p>',
    '<p>In the full language you would write it by matching on the two cases at',
    'once, which Harper gives as:</p>',
    code('fun map f nil = nil',
         '  | map f (hd::tl) = f(hd) :: map f tl'),
    '<p><small>(Harper 1993, p.29. The vertical bar separates the two clauses;',
    'this console has no clausal definitions, so the same two cases are written',
    'with if/then/else instead.)</small></p>',
    code('let map f l =',
         '  if length l == 0 then nil',
         '  else f (hd l) :: map f (tl l)',
         '',
         'let double n = n * 2',
         'map double [1, 2, 3]',
         '&gt; [2, 4, 6]'),
    '<p>Read it against the definition. The empty case gives back the empty',
    'list. The other case does the work to the head and cons the result onto the',
    'answer for the tail. Nothing else is needed, and no loop appears anywhere.</p>',
    '<h2>And the rest of them</h2>',
    '<p>Every list function has the same skeleton. Once you can write one you',
    'can write all of them.</p>',
    code('let sum l = if length l == 0 then 0 else hd l + sum (tl l)',
         'sum [1, 2, 3, 4]',
         '&gt; 10'),
    code('let count p l =',
         '  if length l == 0 then 0',
         '  else if p (hd l) then 1 + count p (tl l)',
         '  else count p (tl l)'),
    '<p>Harper builds reversal the same way, with an accumulator carried down',
    'the recursion and handed back at the empty case (Harper 1993, p.26):</p>',
    code('let rev l acc =',
         '  if length l == 0 then acc',
         '  else rev (tl l) (hd l :: acc)',
         '',
         'rev [1, 2, 3] nil',
         '&gt; [3, 2, 1]'),
    '<p>Note what the accumulator is doing: each step takes the head off the',
    'front of one list and puts it on the front of another, which reverses the',
    'order for free. Nothing is copied and nothing is assigned to.</p>',
    ...nav('lists'),
    ...foot(host),
  ];
}

