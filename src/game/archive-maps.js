// FIVE PEOPLE MAPPING SOMETHING.
//
// The archive has a road, a brewery, four schools and a great many pages about
// places, and nobody in it had ever drawn one. These are the mappers: amateurs
// mostly, one funded project, each of them working on a thing that a map shows
// and prose cannot.
//
// THE HALESOWEN PAGE PAYS FOR THE WHOLE WEB. Halesowen was a detached part of
// Shropshire, an exclave sitting inside Worcestershire from the Norman period
// until 1844, and its townships included Warley Salop and Lapal, both of which
// are already on pages elsewhere in this corpus under their modern names. A
// reader who has been to the school in Warley or the petrol station at the top
// of Carters Lane finds out here which county those were in, and nothing on
// either page will have told them.
//
// Facts checked: the Counties (Detached Parts) Act 1844; the townships as
// listed; the Lower Swansea Valley Project launched 17 August 1961 under
// Kenneth Hilton at University College of Swansea, funded by Nuffield with the
// Welsh Office, the council and the DSIR, reporting in 1967; twitten in
// Parish's Sussex dialect dictionary of 1875.

