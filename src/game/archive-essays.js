    'society that made it rather than a cause, which is basically what Raymond',
    'Williams argued about television: the box did not create suburban life, the',
    'society that wanted suburban life created the box. This is called social',
    'shaping and it is a good corrective to determinism but it can go too far,',
    'because then the technology does not seem to do anything at all, which is',
    'obviously wrong, a nuclear bomb is not just a symptom.</p>',
    '<p>The third answer, which i find most convincing, comes from Gilbert',
    'Simondon and Bernard Stiegler. Simondon says our whole culture treats',
