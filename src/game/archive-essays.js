    '<hr>',
    '<p>There are two completely different things called “game theory” and people',
    'mix them up all the time, so first i want to seperate them.</p>',
    '<p>The first is the mathematical one, from von Neumann and Morgenstern in',
    'their book <i>Theory of Games and Economic Behaviour</i> (1944). This is not',
    'about fun at all. A “game” here just means any situation where what happens',
    'to you depends on what other people choose, so you have to think about what',
    'they are thinking. The famous example is the prisoners dilemma, where two',
    'people both do the rational thing and both end up worse off than if they had',
    'trusted each other. This is a very cold idea of life, everyone calculating,',
    'and it came out of the cold war and nuclear strategy which explains a lot.</p>',
    '<p>The second is the opposite, and it is about play. Johan Huizinga in',
    '<i>Homo Ludens</i> (1938) argues that play is older than culture and that',
    'culture actually comes OUT of play — law, war, poetry, all started as kinds',
    'of contest. Play happens in a “magic circle”, a special time and place with',
    'its own rules that do not apply outside (the pitch, the board, the',
    'playground). Roger Caillois took this and made categories of games:',
    'competition, chance, pretending, and vertigo (like spinning until you are',
    'dizzy), which i thought was a nice list.</p>',
    '<p>So is life a game? In the von Neumann sense, treating life as a game is',
    'exactly the problem — it makes everyone into a calculating player and there',
    'is no room for trust, which the prisoners dilemma shows is self-defeating.',
    'In the Huizinga sense it is more hopeful, because play is free, you choose',
    'to enter the magic circle and you can leave. A game you cannot leave is not',
    'really play, it is just a trap with rules.</p>',
    '<p>My conclusion is that calling life a game is dangerous if you mean the',
    'first thing and interesting if you mean the second, and most people who say',
    'it do not know which one they mean.</p>',
