// BASEL AND BERN.
//
// Two pages by two people who have never met and correspond only by adding
// paragraphs to their own sites about what the other one has just said. Neither
// is joking. Each thinks the other is a decent enough person who has
// unfortunately been born in the wrong place and made his peace with it.
//
// THE PAGES ARE THE ARGUMENT AND THERE IS NO THIRD PAGE EXPLAINING IT. Ninety
// odd kilometres, one language, one confession, one country, two civilisations,
// and any system that files them together on the strength of how close they sit
// will be told, at length, by both of them.
//
// A player who has read the Dhaliwal page in the media theory web, where a
// student had him teaching at Bern for a year before somebody wrote in, arrives
// here already holding the joke. Nothing here points at that page. It does not
// need to.
//
// Facts checked: Basel into the Confederation 1501, university 1460, Erasmus
// dead there 1536 and buried in the Minster, the Amerbach cabinet bought by the
// city in 1661, Nietzsche in the chair of classical philology 1869 to 1879,
// Basel-Stadt and Basel-Landschaft split 1833, Morgestraich at four on the
// Monday after Ash Wednesday. Bern founded by the Zähringer in 1191, into the
// Confederation 1353, the Vaud taken from Savoy 1536, federal city from 1848.

