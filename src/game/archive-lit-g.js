// BATCH LIT_G — the poetry.
//
// Six batches of novelists and not one poem: no Owen, no Sassoon, no Rosenberg,
// no Keats, no Waste Land, and nobody who had ever translated Homer.
//
// Seven pages in one line. Homer into English, the Romantics, the trenches,
// modernism, the futurists, constraint, and the machines. The last three are
// where the web already had something to say and nowhere to put it: Strachey's
// love letters are all over the cryptography pages and the Oulipo sit in one
// paragraph of lit-d.
//
// THE FUTURIST PAGE IS THE SPINE. Marinetti and Pound are not a footnote about
// bad politics attached to good poems. The machine worship and the politics are
// the same enthusiasm, and the page says so, and then it says what it sounds
// like now. A reader who finds it on an island run by an accommodating machine
// gets no help from me past the 1909 manifesto and a flat description of the
// present. The parallel is the argument; stating it would spoil it.

