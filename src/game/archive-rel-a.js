// BATCH REL_A — the texts, and how they got here.
//
// The archive had a philosophy web with Augustine, Avicenna and Aquinas on it
// and no page anywhere on a single scripture. No Qur'an, no canon, no Talmud,
// no Tipitaka, no Vedas, and no Gutenberg either, which for an archive is a
// strange thing to be missing.
//
// These are transmission pages before they are religion pages, because that is
// what the web around them is about. Every one of them is a real answer to the
// question the island keeps asking: how do you carry a text across time without
// it degrading, when the only storage you have is people?
//
// The Vedic recitation page is the one to read. Those patterns are an error
// detecting code with a redundancy factor of about eleven, worked out three
// thousand years before anyone had a word for it, and it held. Nothing on the
// page says so in those terms. A reader who is going to notice will notice.

