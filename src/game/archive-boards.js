// BEFORE THE WEB: BOARDS, AND THE OTHER KIND OF CHANNEL.
//
// Four pages about talking to strangers at a distance without a web. Two of
// them are dial-up boards, one is the man who kept insisting the tools should
// be in ordinary hands, and one is what people used before any of it: a radio
// set in a car, forty channels, and a whole language invented to fit them.
//
// THE BRIGHTON BOARD IS THE ONE WITH NO SOURCES, and it says so on itself.
// Local boards left no record: a few hundred people, one telephone line, a hard
// disk in a bedroom, and nothing kept. It is written as memory and flagged as
// memory.
//
// Fastnet next to it is a real Brighton company and its page is built from the
// company's own account of itself, which is why it reads like one.
//
// The CB page is the joke and does not say so. Forty channels of people who had
// never met, inventing handles, running a shared language, policing their own
// etiquette and getting raided for it, twenty years before any of the pages
// around it in this archive.

