  'procedures, such as sysopen, sysread, syswrite, sysspawn, syssleep, and so on.',
  'This required more space, but was far more convenient.</p>',
  '<p>He was also able to add several novel mechanisms of which perhaps one of the',
  'most important was a collection of procedures made available to users, for',
  'planting instructions for the Pop-11 virtual machine, which could then be',
  'compiled to machine code and run. (I think the original idea for doing this kind',
