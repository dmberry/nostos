  'facilities for Prolog, provides full lexical scoping, and other features that',
  'were not in POP2, WPOP, or early versions of Pop-11.</p>',
  '<p>While language development went on, we were also able to extend the teaching',
  'and programming environment. This included provision of user-extendable search',
  'lists for program libraries and documentation libraries. We also extended the',
  'editor so that it could be a general purpose interface both for browsing code',
  'and documentation and for interaction with programs: the editor buffer was a',
  'data structure that both users and programs could write into and read from. This',
  'made it a suitable interface for a variety of tools including simple graphics',
  'tools, an electronic mail front end, a text formatter, and others.</p>',
  '<p>As new languages were added to Poplog it became necessary to tailor the',
