  '<h2>Miscellaneous developments</h2>',
  '<p>Over the last few years, under the pressure of requirements from users, a',
  'number of further extensions were made, such as provision of built in mechanisms',
  'for vectors of signed integers, new "fast_" procedures for improved efficiency,',
  'a generalised signal handling mechanism, improved tracing and debugging',
  'facilities, extensions to the external language interface, more flexible',
