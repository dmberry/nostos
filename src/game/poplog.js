  // ---- The birth of Poplog Pop-11 ---------------------------------------
  '<h2>The birth of Poplog Pop-11</h2>',
  '<p>In 1981 the Sussex University Computing Centre replaced its ICL machine with',
  'a group of VAX11/780 computers, at last providing a good interactive service,',
  'and the opportunity to develop programs with a big address space (though each',
  'machine initially had only 2.5Mbytes memory).</p>',
  '<p>By then our courses had grown and the PDP11/40 was unable to cope, so we',
  'desperately needed to transfer our teaching to the bigger machines. We hired',
  'John Gibson in the summer of 1981, and by a tortuous route he managed, at',
  'amazing speed, to re-implement Pop-11 on the VAX running VMS, in time for us to',
  'start teaching in October. The bootstrapping process made use of Steve Hardy\'s',
  'PDP11 Pop-11 written in Unix assembler, another Pop-11 he wrote in C, and',
  'finally John Gibson\'s Pop-11 written in Pop-11 to run on the VAX. Programs to',
  'translate the new Pop-11 system sources into VAX VMS assembler were written in',
  'Pop-11, so a Pop-11 system was required to run these programs in order to do the',
  'translation. The output files could then be assembled, linked and run. The full',
  'story of that extraordinary bootstrapping operation should be told in print some',
  'day.</p>',
  '<p>All this would not have been possible without the co-operation of the',
  'Experimental Psychology laboratory, which allowed us to use their VAX for some',
  'of the development work before the new machines were available in the Computing',
  'Centre.</p>',
  '<p>The VAX Pop-11 compiler was not completed until a few hours before our first',
  'batch of students came into the terminal room and attempted to compile and run',
  'our "Eliza" demonstration program. Being a first draft compiler it was very',
  'slow, and with so many students all simultaneously asking it compile a lengthy',
  'file we almost ground the VAX to a halt. But it worked, and, once compiled, the',
  'Eliza program ran at a reasonable speed, using a new version of the pattern',
  'matcher written in Pop-11.</p>',
  '<p>Both compilation and execution speeds have been enormously increased since',
  'then.</p>',
  '<p>At that time we decided to enrich the syntax of Pop-11 with a wide range of',
  'looping constructs, and also decided that all syntax closers should be formed by',
  'prefixing "end" to the opener. Thus having played with forms like "while ... do',
  '... enddo" we eventually settled for "while..do...endwhile",',
  '"define....enddefine" etc. However, there were still plenty of POP2 users that',
  'we wished to convert, so some of the POP2 (and WPOP) syntax was still',
  'accommodated, including "function.....end" and the use of "close" to terminate',
