  // ---- The birth of Pop-11 ----------------------------------------------
  '<h2>The birth of Pop-11</h2>',
  '<p>Having chosen our machine and our language, we tried to get hold of a POP2',
  'for the PDP11 computer. Various implementation projects were unearthed,',
  'including one in India, but they all had unpredictable finishing dates, so',
  'Steve sat down in the Summer of 1975 and by next January we were able to start',
