  'still use it. (It should be replaced by a multi window interface on the X',
  'Windows system.)</p>',
  '<p>Released from the 32Kword address space limitation John Gibson was able to',
  'restore many of the features of POP2 and WPOP, including dynamic lists, user',
  'definable record and vector classes, hashed properties, newanyarray, saved',
  'images, "lightweight processes", sections and other features, some of them',
  'described below. Many of these facilities were generalised in Pop-11, and some',
  'of the generalisations are described below.</p>',
  '<p>The Pop-11 process mechanism provided the main process facilities that were',
