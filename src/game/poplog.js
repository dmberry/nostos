  'all languages, and switch its defaults automatically depending on which language',
  'was currently in use. This raised a number of deep problems that have not yet',
  'been fully resolved, including the problem of coping elegantly with a file that',
  'includes commands in different languages: e.g. it can be a problem for the',
  'editor to decide automatically precisely which language is the "current" one.',
  'E.g. if you ask for help file while editing a prolog file with the cursor',
