  'instance because "end" and "close" are syntax words.</p>',
  '<p>There were two very important changes introduced in VAX Pop-11. The first was',
  'that the language no longer used an interpreted intermediate language. Instead',
  'procedures were compiled all the way to machine code. Secondly the new VAX',
  'Pop-11 system was mostly written in Pop-11 plus a few assembler files. This',
  'meant that from now on development work was going to be much easier as many',
  'extensions could be tried out interactively in a running Pop-11 system and then',
  'later built in to the system. This enormously speeded up subsequent development,',
  'and allowed many extensions to the system to be thoroughly tested before they',
  'were added.</p>',
  '<p>The editor VED was such an extension. Steve Hardy wrote a first draft in',
  'Pop-11 in about three weeks, around August 1981, testing it on the PDP11 as the',
  'VAX Pop-11 was not yet ready. I then took VED over, moved it onto the VAX and',
  'gave it the ability to handle more than one window on the screen. Later this',
  'version was built into the Pop-11 system so that users did not have to recompile',
  'it each time. This split-screen version of VED was meant to be a temporary patch',
  'until we had a proper multi-window editor (as in the Poplog LIB WINDOWS',
  'library), but somehow the temporary patch remained the standard VED interface',
