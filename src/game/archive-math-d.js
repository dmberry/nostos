    'add the missing truth as a new axiom, but the enlarged system then has a fresh',
    'truth of its own that it cannot reach. The gap never closes.</p>',
    '<img class="indie-pic" src="assets/media/web/math/godel-01.jpg" alt=""><span class="indie-cap">Kurt Godel (public domain)</span>',
