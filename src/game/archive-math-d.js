    'formula and every proof, in a systematic way, so that statements ABOUT the',
    'system (this formula is well formed, this sequence is a proof of that',
    'conclusion) become ordinary statements ABOUT numbers. Mathematics is made to',
    'talk about its own grammar by talking about arithmetic. Once syntax has been',
    'turned into arithmetic, a formula can refer, through its code number, to',
    'itself.</p>',
    '<p>With that in hand Godel builds a sentence G that, decoded, says of itself:',
    '<i>this sentence has no proof in the system</i>. Now ask whether G is',
    'provable. If the system could prove G, then G would be false, and the system',
    'would have proved a falsehood, so it would be inconsistent. If the system is',
