// SMETHWICK.
//
// The Black Country web had the Hagley Road, Bearwood, Halesowen and four
// schools, and Smethwick appeared only as a place further down and to the
// right. It was the biggest gap in the local corpus: the brewery that employed
// the town, the glassworks that glazed the Crystal Palace, and the 1964
// election, which is the single most written-about thing that ever happened
// there and had no page at all.
//
// House rules inherited from archive-blackcountry.js and kept exactly: local
// first-person, signed with a board handle, buses and shops as the unit of
// description, corrections invited to the board. Nobody here is performing
// nostalgia. They are settling arguments.
//
// ON THE ELECTION. It is stated flatly, with the dates, and the page does not
// tell the reader what to feel about it. The slogan is described rather than
// printed, which is what a careful local page in 2001 would do, and which is
// also the right call here. Malcolm X was on Marshall Street on 12 February
// 1965 and was killed on the 21st. Those two dates next to each other do all
// the work that is needed.

