    'because it looks finished and authoritative, and because it hides its own',
    'choices. To plot a person on a map you must decide they were <i>somewhere</i>,',
    'exactly, when the record may only say a region, a rumour, a route. The clean',
    'dot on the clean coastline can erase the ambiguity, the movement, the not-',
    'knowing that was the truest thing in the archive. Posner does not tell people',
    'to stop making maps. She tells them to notice what the map made them throw',
    'away in order to be drawn, and to keep the discarded thing in view.</p>',
    '<p>In her much-circulated piece "What\'s Next: The Radical, Unrealized Potential',
    'of Digital Humanities" she pushes further and asks the field to be braver. If',
    'DH really can rebuild the categories rather than inherit them, then it should',
    'take on race, gender and power at the level of the data model itself, not as a',
    'topic bolted on afterwards but as a challenge to how the data is shaped in the',
    'first place. The unrealised potential is a DH that questions its own',
    'infrastructure, not one that merely runs faster on the old assumptions.</p>',
    '<div class="fs-aside"><p><b>For the teacher.</b> If you want to see the counting',
