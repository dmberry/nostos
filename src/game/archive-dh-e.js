    '"Money and Time" she argues that digital humanists too often accept, without',
    'noticing, the categories baked into off-the-shelf software: the spreadsheet',
    'that wants every person to be one clean row, the database that will not let a',
    'category be uncertain, the map that insists a life happened at a single point.',
    'These tools were built to run companies, and they carry the assumptions of the',
    'people who built them. To use them uncritically is to import those assumptions',
    'into the humanities along with the convenience.</p>',
