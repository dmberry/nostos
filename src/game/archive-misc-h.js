// THREE COLLEGES, A DOG, A BEER AND A BUS.
//
// Loose ends, and two of them turn out to belong to the Black Country cluster
// rather than to their own subjects.
//
// MANSFIELD IS THE FIND. It is an Oxford college that was moved there from
// BIRMINGHAM: Spring Hill College, a Congregational foundation, transplanted in
// 1886 to be the first place at Oxford for Nonconformists, who had been barred
// by the tests for centuries. A reader who has come through the Gospel Hall and
// Brethren pages arrives at an Oxford college founded by exactly the people
// those pages are about.
//
// And the No. 9 already exists in this corpus as one line on somebody's
// homepage: "9 City - Hagley Rd - Bearwood - Quinton", with the note that it
// does not go to Quinton any more and the 9A does. That line is the seed. The
// timetable page is written to be consistent with it and says the same thing
// about the 9A without repeating the joke.

