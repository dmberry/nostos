// PUBLIC SERVICE BROADCASTING — batch A, the institutions.
//
// The `tv` web has the programmes and the `mt` web has the theory. Nobody had
// written about broadcasting as an INSTITUTION: who paid for it, who was
// allowed to say what on it, and what a public was supposed to be. That is what
// these are.
//
// Dates, charters, committee names and testimony are real. The fans are not.
//
// The thread running under all of it, never stated on any page: every one of
// these organisations was set up on the principle that a channel reaching
// everybody must answer to somebody other than whoever owns it. On an island
// run by machines nobody elected, a player who reads them will draw the line
// without help.

