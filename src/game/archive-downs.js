// THE DOWNS ABOVE LEWES, AND HOW TO WALK ON THEM.
//
// Two pages by one walker. The hill first, because it is a specific hill with
// a specific clump on it that people navigate by from twenty miles away, and
// then the rules, which are the sort of thing that gets written by somebody who
// has spent years finding gates left open.
//
// THE NAME IS THE PAGE. Blackcap and Mount Harry are two names for ground that
// people have moved between for seven centuries, and Henry III put an army on
// it in 1264 and lost. A hill that a walker treats as scenery was a position.
//
// Checked: 206 metres; 623 acres; National Trust since 1993; the Clayton to
// Offham Escarpment SSSI; Mount Harry as the older name and the 1264 battle;
// the clump visible from the High Weald. The Countryside Code is quoted in
// substance rather than word for word, because the wording has changed several
// times and the page is honest that it is paraphrasing.

