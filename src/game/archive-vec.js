// THE VOCABULARY IS CHECKED HERE. The level at which this work operates is the
// MEDIUM. Not a layer underneath a truer surface, not a base with a
// superstructure on top: the vector medium is the constitutive ground of
// contemporary machine intelligence, which is the whole reason for calling it a
// medium. The word for the thing beneath is not used on these pages at all.
//
// Also not used: the McLuhan slogan. The interest is in the medium itself, in
// what it does to meaning, not in restating that a medium carries a message.
//
// Every concept here is real and consistent with the published position: the
// singular vector medium as distinct from Impett and Offert's plural vector
// media, the two implosions, vector logic as proximity replacing exclusion, the
// negation deficit, the three levels, and the binding of measurement to
// critique. The research page is a real programme with real open questions, and
// a player who reads it carefully will find several of them being answered,
// badly, by the machine running the island.

