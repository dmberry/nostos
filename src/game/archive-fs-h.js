    'Adorno and, in the next round, the younger Jürgen Habermas. On the other, the',
    'critical rationalists, Karl Popper and, more combatively, Hans Albert. It',
    'began at a conference of the German Sociological Association and spilled into',
    'essays and replies for years.</p>',
    '<h2>What they were actually fighting about</h2>',
    '<p>Not whether to be rigorous. Both sides wanted rigour. The quarrel was over',
    'what rigour in the study of society could even mean.</p>',
    '<p>Popper’s position, roughly. Science, including social science, proceeds by',
    'proposing hypotheses and trying hard to refute them. You cannot verify a',
    'theory once and for all, you can only fail to falsify it so far. So the honest',
    'method is piecemeal: state a clear conjecture, test it against the facts, throw',
    'it out if it breaks. Grand claims about “society as a whole” are not testable',
    'and so are not knowledge. Keep it modest, keep it checkable, reform in small',
    'steps.</p>',
    '<p>Adorno’s answer. Society is not a heap of separate facts you can test one at',
    'a time, because the facts are already shaped by the whole they belong to. The',
    '“data” a positivist treats as neutral are products of a particular social',
    'order, and to take them at face value is quietly to endorse that order. Critical',
    'theory insists on grasping the TOTALITY, the system that makes the individual',
    'facts what they are, even though the totality is never a thing you can point at',
    'and measure. Method that refuses the whole ends up describing the surface and',
    'calling it the world.</p>',
    '<h2>Value-freedom</h2>',
    '<p>Under this sat the older question of value-freedom, inherited from Max',
    'Weber. Popper and Albert held that science should separate factual claims from',
