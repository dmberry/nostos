    'itself a value, and a convenient one, because a social science that brackets',
    'all judgement about whether the arrangement is just quietly accepts that it is.',
    'You cannot study a false society from nowhere. The choice is only whether your',
    'values are examined or hidden.</p>',
    '<hr>',
    '<h2>Controversy</h2>',
