// BATCH REL_B — the splits, and the line that runs under all of it.
//
// The philosophy web already has Plotinus, Augustine, Avicenna, Averroes,
// Maimonides, Aquinas, Scotus and Ockham as individual thinkers, and no page
// anywhere explaining that they are one argument being handed along. That is
// the neoplatonism page, and it is the reason this batch exists.
//
// THE ISNAD PAGE IS THE OTHER ONE. Grading a report by the chain of people who
// carried it, keeping biographical files on every transmitter so the chain can
// be checked, and marking the result sound, fair or weak: that is provenance,
// done properly, in the ninth century. The player is on an island being handed
// statements by a system that will not say where they came from. The page does
// not mention that. It describes ninth-century Persia and stops.

