    'framed as a law of NATURE, not a rule for architects. Sullivan was reaching',
    'for the biologist’s world, the shell that fits the creature, the branch that',
    'fits the tree, the eagle whose shape is its flight. He had drunk deep of the',
    'nineteenth century’s fascination with organic form, and behind him stands the',
    'American sculptor Horatio Greenough, who a generation earlier had praised the',
