//   node tools/gen-card-titles.mjs
//
// Writes api/_titles.mjs: every address the cached web can answer for, mapped to
// the title that page already calls itself by. Aliases are resolved here, so
// `retroai` and `usc.edu/retroai` both appear and the share-card function needs
// no alias table of its own.
//
// WHY A GENERATED FILE rather than importing the corpus at request time. The
// share card runs as a serverless function on Vercel, and a function reaching up
// out of /api into ../src to import four modules is the fragile part of the whole
// arrangement: it depends on the bundler tracing those imports correctly in a
// repo with no package.json. This game is live. A generated map keeps everything
// the function needs inside /api, so the worst a bundling change can do is stale
// data rather than a broken deployment.
//
// The obvious cost is drift, which is this project's recurring failure, so
// test/card-titles.test.js regenerates and compares. Adding a page to the corpus
// without re-running this fails the suite.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { ARCHIVED_SITES, DEPARTMENTS, UNIVERSITIES } from '../src/game/archive.js';
import { CACHE_ALIASES } from '../src/game/net.js';

export function buildTitles() {
  const t = {};
  for (const s of ARCHIVED_SITES) {
    if (s && s.domain) t[s.domain] = String(s.title || s.name || s.domain);
  }
  for (const [key, d] of Object.entries(DEPARTMENTS)) {
    if (d) t[key] = String(d.title || key);
  }
  for (const u of (Array.isArray(UNIVERSITIES) ? UNIVERSITIES : Object.values(UNIVERSITIES))) {
    if (u && u.domain && !t[u.domain]) t[u.domain] = String(u.name || u.title || u.domain);
  }
  // Aliases resolve to whatever their target already says.
  for (const [alias, target] of Object.entries(CACHE_ALIASES)) {
    if (t[target]) t[alias] = t[target];
  }
  return Object.fromEntries(Object.entries(t).sort(([a], [b]) => a.localeCompare(b)));
}

export function render(titles) {
  const rows = Object.entries(titles)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n');
  return `// GENERATED by tools/gen-card-titles.mjs — do not edit by hand.
// Every address the cached web can answer for, with the title that page already
// calls itself by. Aliases are resolved. Regenerate after adding a page:
//   node tools/gen-card-titles.mjs
// test/card-titles.test.js fails if this drifts from the corpus.
export const TITLES = {
${rows}
};
`;
}

const OUT = join(fileURLToPath(new URL('.', import.meta.url)), '..', 'api', '_titles.mjs');

if (import.meta.url === `file://${process.argv[1]}`) {
  const titles = buildTitles();
  writeFileSync(OUT, render(titles));
  console.log(`wrote ${OUT}`);
  console.log(`${Object.keys(titles).length} addresses`);
}
